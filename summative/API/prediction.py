"""
prediction.py — Maternal Health Regression API (Task 2)

Endpoints:
  GET  /            -> redirects to Swagger UI docs
  POST /predict      -> single prediction from the current best model
  POST /retrain       -> upload a new CSV to retrain the model in place
  GET  /docs          -> Swagger UI (auto-generated by FastAPI)
"""

import os
import shutil
import tempfile

from fastapi import FastAPI, UploadFile, File, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import RedirectResponse

from schemas import MaternalHealthInput, PredictionResponse, RetrainResponse
from model_utils import predict_one, retrain_from_csv

app = FastAPI(
    title="Maternal Health Access — Regression API",
    description=(
        "Predicts maternal mortality ratio for a Sub-Saharan African country "
        "profile from health-access indicators, using the best-performing "
        "regression model selected in Task 1 (Ridge Regression)."
    ),
    version="1.0.0",
)

# ---------------------------------------------------------------------------
# CORS (Cross-Origin Resource Sharing) middleware
# ---------------------------------------------------------------------------
# WHAT THIS API ALLOWS AND WHY — deliberately NOT using a wildcard origin:
#
# allow_origins: an explicit, named list of the only clients that should be
# calling this API — the Flutter mobile app's local dev server, its web
# build origin, and this API's own Render domain (useful for Swagger UI's
# "Try it out" button, which calls from the same origin). Read from an
# environment variable so the real deployed frontend URL can be added
# without touching code:
#   - "http://localhost:*" ports cover local Flutter web development/testing
#   - the production frontend origin (set via ALLOWED_ORIGINS once known)
# A generic "*" was avoided on purpose: this API's /retrain endpoint can
# overwrite the deployed model, so allowing literally any website to call
# it cross-origin is a real risk worth closing off, even though there's no
# user login involved.
#
# allow_methods: restricted to GET and POST only — the API has no PUT,
# DELETE, or PATCH routes, so allowing them would be unused attack surface.
#
# allow_headers: restricted to the two headers clients actually need to
# send (Content-Type for JSON bodies, Authorization reserved for future
# use) rather than a blanket "*".
#
# allow_credentials: False — the API uses no cookies or session-based auth,
# so credentialed cross-origin requests are unnecessary and explicitly
# disabled.
_default_origins = "http://localhost:3000,http://localhost:8080,http://127.0.0.1:8000"
ALLOWED_ORIGINS = [o.strip() for o in os.getenv("ALLOWED_ORIGINS", _default_origins).split(",")]

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Authorization"],
)


@app.get("/", include_in_schema=False)
def root():
    """Redirect the base URL straight to the Swagger UI docs."""
    return RedirectResponse(url="/docs")


@app.post("/predict", response_model=PredictionResponse)
def predict(payload: MaternalHealthInput):
    """
    Accepts a single country's health-access profile and returns the
    predicted maternal mortality ratio from the current best model.
    """
    try:
        prediction, model_name = predict_one(payload.dict())
    except FileNotFoundError:
        raise HTTPException(
            status_code=500,
            detail="Model artifacts not found on server. Ensure best_model.pkl, "
                   "scaler.pkl, and feature_cols.pkl were deployed alongside the app.",
        )
    return PredictionResponse(
        model_used=model_name,
        input_features=payload,
        predicted_maternal_mortality_ratio=prediction,
    )


@app.post("/retrain", response_model=RetrainResponse)
def retrain(file: UploadFile = File(...)):
    """
    Upload a CSV containing the feature columns plus the target column
    (maternal_mortality_ratio) to retrain the model in place. The new
    model and scaler overwrite the deployed artifacts immediately, so
    subsequent /predict calls use the freshly retrained model.
    """
    if not file.filename.endswith(".csv"):
        raise HTTPException(status_code=400, detail="Please upload a .csv file")

    with tempfile.NamedTemporaryFile(delete=False, suffix=".csv") as tmp:
        shutil.copyfileobj(file.file, tmp)
        tmp_path = tmp.name

    try:
        metrics = retrain_from_csv(tmp_path)
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e))
    finally:
        os.remove(tmp_path)

    return RetrainResponse(
        message="Model retrained and redeployed successfully.",
        **metrics,
    )
